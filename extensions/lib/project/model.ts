// Reply reading

type Json = Record<string, any>;

function readJson(path: string, what: string): Json {
  let text: string;
  try {
    text = readFileSync(path, "utf8");
  } catch (error) {
    throw new ProjectModelError(`Cannot read ${what} ${path}: ${(error as NodeJS.ErrnoException).code ?? String(error)}. Reconfigure the project to regenerate the CMake File API reply.`);
  }
  try {
    const data = JSON.parse(text);
    if (!data || typeof data !== "object") throw new Error("not a JSON object");
    return data;
  } catch (error) {
    throw new ProjectModelError(`The ${what} ${path} is incomplete or malformed (${error instanceof Error ? error.message : String(error)}). Reconfigure the project to regenerate it.`);
  }
}

function clientReply(index: Json, indexFile: string, kind: string): string {
  const entry = index.reply?.[FILE_API_CLIENT]?.[kind];
  if (!entry) throw new ProjectModelError(`The reply index ${indexFile} has no ${kind} reply for ${FILE_API_CLIENT}; the query was not written before this configure.`);
  if (typeof entry.error === "string") throw new ProjectModelError(`CMake could not answer the ${kind} query: ${entry.error}`);
  if (typeof entry.jsonFile !== "string") throw new ProjectModelError(`The ${kind} entry in ${indexFile} names no reply file.`);
  return join(dirname(indexFile), entry.jsonFile);
}

function resolveBacktraces(graph: Json | undefined, sourceDir: string): (index: unknown) => readonly BacktraceFrame[] {
  const nodes: Json[] = Array.isArray(graph?.nodes) ? graph.nodes : [];
  const files: string[] = (Array.isArray(graph?.files) ? graph.files : []).map((file: string) => bestRealPath(resolve(sourceDir, file)));
  const commands: string[] = Array.isArray(graph?.commands) ? graph.commands : [];
  const cache = new Map<number, readonly BacktraceFrame[]>();
  return index => {
    if (typeof index !== "number") return [];
    const cached = cache.get(index);
    if (cached) return cached;
    const frames: BacktraceFrame[] = [];
    const seen = new Set<number>();
    for (let current: number | undefined = index; current !== undefined && nodes[current] && !seen.has(current); current = nodes[current].parent) {
      seen.add(current);
      const node: Json = nodes[current];
      const frame: BacktraceFrame = { file: files[node.file] ?? "" };
      if (typeof node.line === "number") frame.line = node.line;
      if (typeof node.command === "number" && commands[node.command] !== undefined) frame.command = commands[node.command];
      frames.push(Object.freeze(frame));
    }
    const result = Object.freeze(frames);
    cache.set(index, result);
    return result;
  };
}

// KTD10: the CXX languageStandard field, else a -std= flag in the compile fragments, else compiler default.
function groupStandard(group: Json): string | undefined {
  const declared = group.languageStandard?.standard;
  if (typeof declared === "string" && declared) return normalizeStandard(declared);
  for (const fragment of Array.isArray(group.compileCommandFragments) ? group.compileCommandFragments : []) {
    const match = typeof fragment?.fragment === "string" ? fragment.fragment.match(/(?:^|\s)[-/]std[=:](?:c|gnu)\+\+(\w+)/) : null;
    if (match) return normalizeStandard(match[1]);
  }
  return undefined;
}

const unique = <T>(values: T[]) => [...new Set(values)];

interface CtestInfo {
  /** Real paths of executables CTest runs. */
  commands: Set<string>;
  notes: string[];
}

async function readCtest(buildDir: string, exec: Exec, signal?: AbortSignal): Promise<CtestInfo> {
  const info: CtestInfo = { commands: new Set(), notes: [] };
  let output: string;
  try {
    // cwd instead of --test-dir, which needs CTest 3.20.
    const result = await exec("ctest", ["--show-only=json-v1"], { cwd: buildDir, signal, timeout: CTEST_TIMEOUT_MS });
    if (result.code !== 0 || result.killed) {
      const message = [result.stderr, result.stdout].join("\n").trim().split("\n").slice(0, 3).join("\n");
      info.notes.push(`ctest --show-only=json-v1 failed, so no target is classified as a test${message ? `: ${message}` : "."}`);
      return info;
    }
    output = result.stdout;
  } catch (error) {
    info.notes.push(`ctest could not run, so no target is classified as a test: ${error instanceof Error ? error.message : String(error)}`);
    return info;
  }
  let tests: Json[];
  try {
    const data = JSON.parse(output);
    tests = Array.isArray(data?.tests) ? data.tests : [];
  } catch {
    info.notes.push("ctest printed unreadable JSON, so no target is classified as a test.");
    return info;
  }
  const unresolved: string[] = [];
  for (const entry of tests) {
    const program = Array.isArray(entry?.command) ? entry.command[0] : undefined;
    if (typeof program === "string" && program) info.commands.add(bestRealPath(resolve(buildDir, program)));
    else if (typeof entry?.name === "string") unresolved.push(entry.name);
  }
  // Before a build, CTest omits `command` for tests whose executable does not
  // exist yet; the generated CTestTestfile.cmake still names its path.
  if (unresolved.length > 0) {
    const fromTestfiles = readCtestTestfiles(buildDir);
    for (let i = unresolved.length - 1; i >= 0; i--) {
      const program = fromTestfiles.get(unresolved[i]!);
      if (program) { info.commands.add(bestRealPath(resolve(buildDir, program))); unresolved.splice(i, 1); }
    }
  }
  if (unresolved.length > 0) {
    info.notes.push(`CTest cannot resolve the executable of ${unresolved.length === 1 ? "test" : "tests"} ${unresolved.join(", ")} until it is built, so ${unresolved.length === 1 ? "its target is" : "their targets are"} not classified as tests yet.`);
  }
  return info;
}

/** Maps test names to their program from every `CTestTestfile.cmake` under the build directory. */
function readCtestTestfiles(buildDir: string): Map<string, string> {
  const programs = new Map<string, string>();
  const pending = [buildDir];
  while (pending.length > 0) {
    const dir = pending.pop()!;
    let text: string;
    try { text = readFileSync(join(dir, "CTestTestfile.cmake"), "utf8"); } catch { continue; }
    for (const match of text.matchAll(/^add_test\(\s*(?:\[(=*)\[(.+?)\]\1\]|"([^"]+)"|([^\s")]+))\s+"([^"]+)"/gm)) {
      programs.set(match[2] ?? match[3] ?? match[4]!, match[5]!);
    }
    for (const sub of text.matchAll(/^subdirs\("([^"]+)"\)/gm)) pending.push(resolve(dir, sub[1]!));
  }
  return programs;
}

function deepFreeze<T>(value: T): T {
  if (value && typeof value === "object" && !Object.isFrozen(value)) {
    Object.freeze(value);
    for (const child of Object.values(value)) deepFreeze(child);
  }
  return value;
}

export interface LoadProjectModelOptions {
  /** A reply `index-*.json`, such as `readReplyState(buildDir).lastGood`. */
  indexFile: string;
  /** Runs `ctest` for test classification (KTD9). */
  exec: Exec;
  signal?: AbortSignal;
}

/**
 * Read a File API reply into a project model (KTD1). Throws ProjectModelError when the index or a
 * reply file it references is missing, partial or malformed.
 */
export async function loadProjectModel(options: LoadProjectModelOptions): Promise<ProjectModel> {
  const { indexFile, exec, signal } = options;
  const index = readJson(indexFile, "CMake File API reply index");
  const codemodelFile = clientReply(index, indexFile, "codemodel-v2");
  const cmakeFilesFile = clientReply(index, indexFile, "cmakeFiles-v1");
  const codemodel = readJson(codemodelFile, "codemodel reply");
  const cmakeFiles = readJson(cmakeFilesFile, "cmakeFiles reply");

  const paths = codemodel.paths;
  const configuration = Array.isArray(codemodel.configurations) ? codemodel.configurations[0] : undefined;
  if (typeof paths?.source !== "string" || typeof paths?.build !== "string" || !configuration || !Array.isArray(configuration.targets)) {
    throw new ProjectModelError(`The codemodel reply ${codemodelFile} is incomplete. Reconfigure the project to regenerate it.`);
  }
  const sourceRoot = bestRealPath(paths.source);
  const buildDir = bestRealPath(paths.build);
  const ctest = await readCtest(buildDir, exec, signal);

  const entries: Json[] = configuration.targets;
  const raw = entries.map(entry => {
    if (typeof entry?.jsonFile !== "string") throw new ProjectModelError(`The codemodel reply ${codemodelFile} lists a target without a reply file.`);
    return readJson(join(dirname(indexFile), entry.jsonFile), "target reply");
  });
  const nameById = new Map<string, string>(raw.map(target => [target.id, target.name]));

  const targets = raw.map((target): ProjectTarget => {
    const sourceDir = bestRealPath(resolve(sourceRoot, target.paths?.source ?? "."));
    const backtrace = resolveBacktraces(target.backtraceGraph, sourceRoot);
    const groups: Json[] = Array.isArray(target.compileGroups) ? target.compileGroups : [];
    const sources = (Array.isArray(target.sources) ? target.sources : []).map((source: Json): ProjectSource => {
      const path = bestRealPath(resolve(sourceRoot, source.path));
      const group = typeof source.compileGroupIndex === "number" ? groups[source.compileGroupIndex] : undefined;
      const entry: ProjectSource = { path, isGenerated: source.isGenerated === true || isWithin(buildDir, path), backtrace: backtrace(source.backtrace) };
      if (group && typeof group.language === "string") {
        entry.language = group.language;
        const standard = groupStandard(group);
        if (standard !== undefined) entry.standard = standard;
      }
      return entry;
    });
    const artifacts = (Array.isArray(target.artifacts) ? target.artifacts : [])
      .map((artifact: Json) => bestRealPath(resolve(buildDir, artifact.path)));
    const type = String(target.type);
    const isTest = type === "EXECUTABLE" && artifacts.some((artifact: string) => ctest.commands.has(artifact));
    const kind: TargetKind = isTest ? "test" : type === "EXECUTABLE" ? "executable" : type.endsWith("_LIBRARY") ? "library" : "utility";
    const result: ProjectTarget = {
      name: String(target.name),
      id: String(target.id),
      type,
      kind,
      isProjectTarget: isWithin(sourceRoot, sourceDir) && !isWithin(buildDir, sourceDir) && !isInSkippedDir(sourceRoot, sourceDir),
      sourceDir,
      sources,
      includeDirs: unique(groups.flatMap(group => (Array.isArray(group.includes) ? group.includes : [])
        .map((include: Json) => bestRealPath(resolve(sourceRoot, include.path))))),
      defines: unique(groups.flatMap(group => (Array.isArray(group.defines) ? group.defines : []).map((define: Json) => String(define.define)))),
      dependencies: unique((Array.isArray(target.dependencies) ? target.dependencies : [])
        .map((dependency: Json) => nameById.get(dependency.id) ?? String(dependency.id))),
      artifacts,
      backtrace: backtrace(target.backtrace),
    };
    const cxxStandard = lowestStandard(groups.filter(group => group.language === "CXX").map(groupStandard));
    if (cxxStandard !== undefined) result.cxxStandard = cxxStandard;
    return result;
  });

  const cmakeRoot = bestRealPath(cmakeFiles.paths?.source ?? sourceRoot);
  const cmakeInputs = unique((Array.isArray(cmakeFiles.inputs) ? cmakeFiles.inputs : [])
    .filter((input: Json) => typeof input?.path === "string" && !input.isGenerated && !input.isExternal && !input.isCMake)
    .map((input: Json) => bestRealPath(resolve(cmakeRoot, input.path))));

  const model: ProjectModel = {
    sourceRoot,
    buildDir,
    indexFile,
    cmakeVersion: String(index.cmake?.version?.string ?? ""),
    configuration: String(configuration.name ?? ""),
    targets,
    cmakeInputs,
    notes: ctest.notes,
  };
  if (Array.isArray(cmakeFiles.globsDependent)) {
    model.globsDependent = cmakeFiles.globsDependent.map((glob: Json): GlobDependency => {
      const entry: GlobDependency = {
        expression: String(glob.expression),
        recurse: glob.recurse === true,
        listDirectories: glob.listDirectories === true,
        followSymlinks: glob.followSymlinks === true,
        paths: (Array.isArray(glob.paths) ? glob.paths : []).map((path: string) => resolve(cmakeRoot, path)),
      };
      if (typeof glob.relative === "string") entry.relative = glob.relative;
      return entry;
    });
  }
  return deepFreeze(model);
}

