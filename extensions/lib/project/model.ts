// Backtraces (KTD7)

export interface DeclaringLocation {
  /** The CMakeLists.txt under the source root that declares the source or target. */
  file: string;
  line: number;
  command?: string;
  /** The leaf frame when it sits elsewhere, such as a wrapper function in a `cmake/*.cmake` module. */
  helper?: BacktraceFrame;
}

/**
 * The location to edit for a source or target (KTD7): the first frame, from the leaf toward the root,
 * whose file is a CMakeLists.txt under `sourceRoot`. Names the leaf as the helper when it differs.
 */
export function declaringLocation(frames: readonly BacktraceFrame[], sourceRoot: string): DeclaringLocation | undefined {
  const index = frames.findIndex(frame => frame.line !== undefined && basename(frame.file) === "CMakeLists.txt" && isWithin(sourceRoot, frame.file));
  if (index < 0) return undefined;
  const frame = frames[index];
  const location: DeclaringLocation = { file: frame.file, line: frame.line! };
  if (frame.command !== undefined) location.command = frame.command;
  if (index > 0) location.helper = { ...frames[0] };
  return location;
}

