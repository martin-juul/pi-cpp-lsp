// Lookups

interface Ownership {
  target: ProjectTarget;
  source: ProjectSource;
}

const ownership = new WeakMap<ProjectModel, Map<string, Ownership[]>>();

function ownershipIndex(model: ProjectModel): Map<string, Ownership[]> {
  let index = ownership.get(model);
  if (!index) {
    index = new Map();
    for (const target of model.targets) {
      for (const source of target.sources) {
        const owners = index.get(source.path) ?? [];
        if (!owners.some(owner => owner.target === target)) owners.push({ target, source });
        index.set(source.path, owners);
      }
    }
    ownership.set(model, index);
  }
  return index;
}

export function findTarget(model: ProjectModel, name: string): ProjectTarget | undefined {
  return model.targets.find(target => target.name === name);
}

/** Every target that lists `path` as a source, compared by real path. */
export function ownersOf(model: ProjectModel, path: string): ProjectTarget[] {
  return (ownershipIndex(model).get(bestRealPath(path)) ?? []).map(owner => owner.target);
}

/** The standard a file must stay valid for: the most restrictive among its owners (KTD7, AE8). Undefined is compiler default. */
export function effectiveStandard(model: ProjectModel, path: string): string | undefined {
  return lowestStandard((ownershipIndex(model).get(bestRealPath(path)) ?? []).map(owner => owner.source.standard));
}
