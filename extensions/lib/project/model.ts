import { existsSync, readFileSync, realpathSync } from "node:fs";
import { basename, dirname, isAbsolute, join, relative, resolve, sep } from "node:path";
import { FILE_API_CLIENT, type Exec } from "./configure.ts";

const CTEST_TIMEOUT_MS = 30_000;

/** A model load failed because the reply is missing, partial or malformed. */
export class ProjectModelError extends Error {
  override name = "ProjectModelError";
}

/** One frame of a CMake backtrace. The outermost frame of a file has no line or command. */
export interface BacktraceFrame {
  /** Absolute path of the CMake file. */
  file: string;
  line?: number;
  /** The command called at this line, e.g. `add_library` or a user function. */
  command?: string;
}

export interface ProjectSource {
  /** Absolute real path; for a file that does not exist yet, the real path of its nearest existing ancestor joined with the rest. */
  path: string;
  /** Marked generated by CMake, or located in the build directory (e.g. `configure_file` output). */
  isGenerated: boolean;
  /** Compile language, absent for sources that are not compiled (headers, rules). */
  language?: string;
  /** Language standard of the source's compile group (KTD10); undefined means compiler default. */
  standard?: string;
  /** Frames from the leaf (the command that added the source) to the root. */
  backtrace: readonly BacktraceFrame[];
}

export type TargetKind = "executable" | "library" | "test" | "utility";

export interface ProjectTarget {
  name: string;
  id: string;
  /** CMake target type, e.g. EXECUTABLE, STATIC_LIBRARY, INTERFACE_LIBRARY, UTILITY. */
  type: string;
  /** `test` for executables whose artifact CTest runs (KTD9). */
  kind: TargetKind;
  /** Source directory under the root and outside any build or dependency directory (KTD6). */
  isProjectTarget: boolean;
  /** Absolute real path of the directory whose CMakeLists.txt defines the target. */
  sourceDir: string;
  sources: readonly ProjectSource[];
  /** Most restrictive C++ standard among the target's CXX compile groups; undefined means compiler default. */
  cxxStandard?: string;
  includeDirs: readonly string[];
  defines: readonly string[];
  /** Names of the targets this target depends on. */
  dependencies: readonly string[];
  /** Absolute paths of the files the target produces. */
  artifacts: readonly string[];
  /** Backtrace of the command that created the target. */
  backtrace: readonly BacktraceFrame[];
}

/** A glob CMake re-checks at build time (`file(GLOB ... CONFIGURE_DEPENDS)`), from cmakeFiles v1.1 (CMake 3.31+). */
export interface GlobDependency {
  expression: string;
  recurse: boolean;
  listDirectories: boolean;
  followSymlinks: boolean;
  relative?: string;
  /** Absolute paths the glob matched at configure time. */
  paths: readonly string[];
}

/** An immutable snapshot of one File API reply. Replace it whole after each configure. */
export interface ProjectModel {
  /** Absolute real path of the top-level source directory. */
  sourceRoot: string;
  /** Absolute real path of the build directory. */
  buildDir: string;
  indexFile: string;
  cmakeVersion: string;
  /** Build configuration name, empty when CMAKE_BUILD_TYPE is unset. */
  configuration: string;
  targets: readonly ProjectTarget[];
  /** Project-local CMake input files (absolute), without generated, external and CMake-bundled ones. */
  cmakeInputs: readonly string[];
  /** Present when CMake reports glob dependencies (CMake 3.31+). */
  globsDependent?: readonly GlobDependency[];
  /** Messages for the briefing, e.g. tests whose executable is not built yet. */
  notes: readonly string[];
}

// ---------------------------------------------------------------------------
// Paths

/** Real path of `path`, or of its nearest existing ancestor joined with the rest when it does not exist. */
export function bestRealPath(path: string): string {
  const absolute = resolve(path);
  try {
    return realpathSync(absolute);
  } catch {
    const parent = dirname(absolute);
    return parent === absolute ? absolute : join(bestRealPath(parent), basename(absolute));
  }
}

const isWithin = (dir: string, path: string) => path === dir || path.startsWith(dir.endsWith(sep) ? dir : dir + sep);

const SKIPPED_DIR = /^(?:\.git|build.*|cmake-build-.*|out|_deps)$/;

/**
 * Whether `path` lies in a directory that drift and project-target checks skip (KTD6): `.git`,
 * `build*`, `cmake-build-*`, `out`, `_deps`, or any directory holding a CMakeCache.txt, between
 * `root` (exclusive) and `path`. Paths outside `root` are not considered skipped.
 */
export function isInSkippedDir(root: string, path: string): boolean {
  const rel = relative(root, path);
  if (rel === "" || rel.startsWith("..") || isAbsolute(rel)) return false;
  let current = root;
  for (const segment of rel.split(sep)) {
    if (SKIPPED_DIR.test(segment)) return true;
    current = join(current, segment);
    if (existsSync(join(current, "CMakeCache.txt"))) return true;
  }
  return false;
}

// ---------------------------------------------------------------------------
// Standards

const STANDARD_ALIASES: Record<string, string> = { "0x": "11", "1y": "14", "1z": "17", "2a": "20", "2b": "23", "2c": "26", "03": "98" };

function normalizeStandard(value: string): string {
  return STANDARD_ALIASES[value] ?? value;
}

// 98 predates 11; later standards order by number.
const standardRank = (standard: string) => {
  const year = Number(standard);
  return Number.isFinite(year) ? (year >= 90 ? 1900 + year : 2000 + year) : Number.POSITIVE_INFINITY;
};

/** The most restrictive (oldest) of the known standards; undefined when none is known. */
export function lowestStandard(standards: Iterable<string | undefined>): string | undefined {
  let lowest: string | undefined;
  for (const standard of standards) {
    if (standard !== undefined && (lowest === undefined || standardRank(standard) < standardRank(lowest))) lowest = standard;
  }
  return lowest;
}

/** "C++14", or "compiler default" when no standard is set (KTD10). */
export function formatStandard(standard: string | undefined): string {
  return standard === undefined ? "compiler default" : `C++${standard}`;
}

